"""Build, check, render and export one stud creature, headless.

    blender -b --factory-startup -P scripts/build.py -- path/to/creature.py [options]

Options:
    --out DIR         where renders, report and exports go (default: <creature folder>/out/<Name>)
    --views a,b,...   preset views to render (default: three_quarter,front,side,back)
    --no-studs        build it without the stud texture (preview and Roblox setup script)
    --pose            also render a test pose (every joint bent) to find gaps at the joints
    --colours         also render each colour mesh on its own (Roblox moderates every mesh separately)
    --export          write <Name>.fbx and <Name>_roblox_setup.luau
    --res WxH         render size (default 960x720)

The creature file defines build(sk) and returns a studkit.Creature. It may `import blockkit as bk`.
Every run writes <Name>_report.txt and <Name>_sheet.png (all the views in one picture).
"""
import bpy, os, sys, math, importlib.util
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import studkit as sk
import blockkit  # noqa: F401  (so creature files can import it)


def args():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    if not argv:
        raise SystemExit(__doc__)
    o = dict(path=os.path.abspath(argv[0]), out=None, views='three_quarter,front,side,back', studs=True, pose=False,
             colours=False, export=False, res=(960, 720))
    i = 1
    while i < len(argv):
        a = argv[i]
        if a == '--out':
            o['out'] = os.path.abspath(argv[i + 1]); i += 1
        elif a == '--views':
            o['views'] = argv[i + 1]; i += 1
        elif a == '--res':
            w, h = argv[i + 1].lower().split('x'); o['res'] = (int(w), int(h)); i += 1
        elif a == '--no-studs':
            o['studs'] = False
        elif a == '--pose':
            o['pose'] = True
        elif a == '--colours' or a == '--colors':
            o['colours'] = True
        elif a == '--export':
            o['export'] = True
        i += 1
    return o


def clean_scene():
    for ob in list(bpy.data.objects):
        bpy.data.objects.remove(ob, do_unlink=True)
    for coll in list(bpy.data.collections):
        bpy.data.collections.remove(coll)


def load(path):
    folder = os.path.dirname(path)
    if folder not in sys.path:
        sys.path.insert(0, folder)
    spec = importlib.util.spec_from_file_location(os.path.splitext(os.path.basename(path))[0], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sheet(paths, out, cols=3):
    """All renders side by side in one PNG (Blender's own image API: no extra Python packages needed)."""
    imgs = []
    for p in paths:
        if os.path.exists(p):
            im = bpy.data.images.load(p)
            w, h = im.size
            px = np.array(im.pixels[:], dtype=np.float32).reshape(h, w, 4)
            imgs.append(px)
            bpy.data.images.remove(im)
    if not imgs:
        return None
    h = max(i.shape[0] for i in imgs)
    w = max(i.shape[1] for i in imgs)
    rows = (len(imgs) + cols - 1) // cols
    cols = min(cols, len(imgs))
    canvas = np.zeros((rows * h, cols * w, 4), dtype=np.float32)
    canvas[..., 3] = 1
    for k, im in enumerate(imgs):
        r, c = k // cols, k % cols
        y0 = (rows - 1 - r) * h          # Blender images start at the bottom row
        canvas[y0:y0 + im.shape[0], c * w:c * w + im.shape[1]] = im
    img = bpy.data.images.new('SK_sheet', cols * w, rows * h, alpha=False)
    img.pixels.foreach_set(canvas.ravel())
    img.filepath_raw = out
    img.file_format = 'PNG'
    img.save()
    bpy.data.images.remove(img)
    return out


def bend_all(rig, deg=14, jaw=22):
    """Test pose: every bone bent a little about its own X axis, jaws opened more."""
    for pb in rig.pose.bones:
        if pb.name == 'Root':
            continue
        pb.rotation_mode = 'XYZ'
        a = jaw if 'Jaw' in pb.name else deg
        pb.rotation_euler = (math.radians(a), 0, 0)
    bpy.context.view_layer.update()


def reset_pose(rig):
    for pb in rig.pose.bones:
        pb.rotation_mode = 'XYZ'
        pb.rotation_euler = (0, 0, 0)
        pb.location = (0, 0, 0)
    bpy.context.view_layer.update()


def luau_setup(d, path):
    name = d.name
    rows = []
    for key, c in d.palette.items():
        kind = 'glow' if key in d.glow else ('smooth' if key in d.smooth else 'stud')
        r, g, b = getattr(c, 'srgb', [round(x * 255) for x in c])
        rows.append('\t["%s"] = {%d, %d, %d, "%s"},' % (key, r, g, b, kind))
    src = '''--[[ %(name)s: Roblox Studio setup (generated by stud-creatures/scripts/build.py)
 1. Import %(name)s.fbx with File > Import 3D (the rig is detected), and insert it into the Workspace.
 2. Paste this whole script into the Command Bar (View > Command Bar) and press Enter.
 It colours every part, makes glowing parts Neon and smooth parts SmoothPlastic, and gives the rest the stud
 material, creating a stud MaterialVariant if the game has none. STUDS = false: the same creature without studs. ]]
local NAME = "%(name)s"
local STUDS = %(studs)s
local PALETTE = {
%(rows)s
}
-- Used only when the game has no stud MaterialVariant yet. These are the community "2022 studs" textures by
-- ReeceTheUncancelable (rbxassetid  / ). To use your own, upload the PNGs from the skill's
-- textures folder (Asset Manager > Images) and put their ids here.
local VARIANT_NAME = "Stud"
local COLOR_MAP = ""
local NORMAL_MAP = ""

local MaterialService = game:GetService("MaterialService")
local variant = nil
if STUDS then
	for _, v in MaterialService:GetDescendants() do
		if v:IsA("MaterialVariant") and string.find(string.lower(v.Name), "stud") then
			variant = v
			break
		end
	end
	if not variant and string.match(COLOR_MAP, "^rbxassetid://%%d+$") and string.match(NORMAL_MAP, "^rbxassetid://%%d+$") then
		variant = Instance.new("MaterialVariant")
		variant.Name = VARIANT_NAME
		variant.BaseMaterial = Enum.Material.Plastic
		variant.ColorMap = COLOR_MAP
		variant.NormalMap = NORMAL_MAP
		variant.StudsPerTile = 1
		variant.Parent = MaterialService
		print("Created MaterialVariant '" .. VARIANT_NAME .. "' in MaterialService")
	end
end

if STUDS and not variant then
	STUDS = false
	warn("No verified stud texture IDs or existing project variant; using plain material until textures are uploaded.")
end

local model = nil
for _, m in workspace:GetDescendants() do
	if m:IsA("Model") and m.Name == NAME then
		model = m
		break
	end
end
assert(model, "No model called " .. NAME .. " in the Workspace: import " .. NAME .. ".fbx first")
local done = 0
for _, p in model:GetDescendants() do
	if p:IsA("MeshPart") then
		local key = p.Name:sub(1, #NAME + 1) == NAME .. "_" and p.Name:sub(#NAME + 2) or p.Name
		local c = PALETTE[key]
		if c then
			p.Color = Color3.fromRGB(c[1], c[2], c[3])
			if c[4] == "glow" then
				p.Material = Enum.Material.Neon
				p.MaterialVariant = ""
			elseif c[4] == "smooth" or not variant then
				p.Material = Enum.Material.SmoothPlastic
				p.MaterialVariant = ""
			else
				p.Material = variant.BaseMaterial
				p.MaterialVariant = variant.Name
			end
			done += 1
		end
	end
end
print(string.format("%%s: %%d parts set up%%s", NAME, done, STUDS and " with studs" or " without studs"))
return {model = model:GetFullName(), partsConfigured = done, studsApplied = STUDS and variant ~= nil, textureUploadNeeded = not variant}
''' % dict(name=name, studs='true' if d.studs else 'false', rows='\n'.join(rows))
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(src)
    return path


def main():
    o = args()
    clean_scene()
    sk.review_scene()
    mod = load(o['path'])
    d = mod.build(sk)
    if not o['studs']:
        d.studs = False
    out = o['out'] or os.path.join(os.path.dirname(o['path']), 'out', d.name)
    os.makedirs(out, exist_ok=True)
    rig, objs = d.finalize()
    r = d.report
    lo, hi = sk.creature_bounds(objs)
    size = hi - lo
    lines = ['%s' % d.name,
             'blocks %d, bones %d, triangles %d (Roblox limit: 20000 per colour mesh)' % (r['blocks'], r['bones'], r['tris']),
             'size in studs: width %.1f, length %.1f, height %.1f (the avatar is about 5 tall)' % (size.x, size.y, size.z),
             'floating pieces (touch nothing): %d' % len(r['floating'])]
    lines += ['  FLOAT %s on %s at %s' % f for f in r['floating']]
    lines.append('coplanar faces of different colours: %d found, %d left after nudging (left ones flicker)' % (r['zfight_fixed'], r['zfight_left']))
    if r['anchored']:
        lines.append('bones with no block (got a hidden anchor so Roblox keeps them): %s' % ', '.join(r['anchored']))
    big = [(c, n) for c, n in r['tris_by_colour'].items() if n > 20000]
    if big:
        lines.append('TOO MANY TRIANGLES in: %s' % ', '.join('%s %d' % b for b in big))
    lines.append('colours: %s' % ', '.join('%s %d' % (c, n) for c, n in sorted(r['tris_by_colour'].items(), key=lambda x: -x[1])))
    renders = sk.shoot(objs, out, d.name, views=o['views'].split(','), res=o['res'])
    # the face close-up: the bone called Head, or for many-headed creatures the highest Head... bone
    heads = [n for n in d.bone_defs if n.startswith('Head')]
    head = d.bone_defs.get('Head') or (max((d.bone_defs[n] for n in heads), key=lambda b: b['head'].z) if heads else None)
    if head:
        c = (head['head'] + head['tail']) / 2
        rad = max((head['tail'] - head['head']).length * 1.5, 2.5)
        # the face is judged from the front (brows, eyes, open mouth) and from three quarters
        renders += sk.shoot(objs, out, d.name + '_head', views=('front', 'three_quarter'), res=o['res'], focus=(c, rad))
    if o['pose']:
        bend_all(rig)
        renders += sk.shoot(objs, out, d.name + '_pose', views=('three_quarter',), res=o['res'])
        reset_pose(rig)
    if o['colours']:
        for ob in objs:
            others = [x for x in objs if x is not ob]
            for x in others:
                x.hide_render = True
            sk.shoot([ob], out, d.name + '_colour_' + ob.name[len(d.name) + 1:], views=('three_quarter',), res=(480, 360))
            for x in others:
                x.hide_render = False
        lines.append('colour renders: one per colour mesh (each one alone must not look like anything inappropriate)')
    lines.append('sheet: %s' % sheet(renders, os.path.join(out, d.name + '_sheet.png')))
    if o['export']:
        fbx, kb = sk.export_fbx(rig, objs, os.path.join(out, d.name + '.fbx'))
        lines.append('exported %s (%d KB) and %s' % (fbx, kb, luau_setup(d, os.path.join(out, d.name + '_roblox_setup.luau'))))
    text = '\n'.join(lines)
    with open(os.path.join(out, d.name + '_report.txt'), 'w', encoding='utf-8') as fh:
        fh.write(text + '\n')
    print('\n' + text)
    print('OUT', out)


main()
