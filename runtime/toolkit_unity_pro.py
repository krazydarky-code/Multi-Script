def csharp_task(body, label, helpers="", usings=()):
    body = "\n".join(("            " + ln) if ln.strip() else ln for ln in body.strip("\n").splitlines())
    helpers = "\n".join(("        " + ln) if ln.strip() else ln for ln in helpers.strip("\n").splitlines()) if helpers else ""
    u = "\n".join("using %s;" % x for x in usings)
    return fill(_WRAP, LABEL=re.sub(r"[^\w .:-]", "", label)[:60], USINGS=u, HELPERS=helpers, BODY=body)


def _balanced(code):
    """Cheap brace/paren/bracket balance check ignoring strings and comments (catches truncated snippets before Unity compiles)."""
    stack, i, n = [], 0, len(code)
    pairs = {")": "(", "]": "[", "}": "{"}
    while i < n:
        ch = code[i]
        if code.startswith("//", i):
            j = code.find("\n", i)
            i = n if j < 0 else j
        elif code.startswith("/*", i):
            j = code.find("*/", i + 2)
            i = n if j < 0 else j + 2
        elif code.startswith('@"', i) or ch == '"':
            verbatim = code.startswith('@"', i)
            i += 2 if verbatim else 1
            while i < n:
                if verbatim and code.startswith('""', i):
                    i += 2
                    continue
                if not verbatim and code[i] == "\\":
                    i += 2
                    continue
                if code[i] == '"':
                    break
                i += 1
        elif ch == "'":
            i += 1
            while i < n and code[i] != "'":
                i += 2 if code[i] == "\\" else 1
        elif ch in "([{":
            stack.append(ch)
        elif ch in ")]}":
            if not stack or stack.pop() != pairs[ch]:
                return False
        i += 1
    return not stack


def parse_marker(text):
    """Pull the MS_RESULT:{...} JSON object out of console output (last one wins)."""
    found = None
    for m in re.finditer(r"MS_RESULT:", text or ""):
        frag = text[m.end():]
        depth, end, in_str, esc = 0, None, False, False
        for i, ch in enumerate(frag):
            if in_str:
                if esc:
                    esc = False
                elif ch == "\\":
                    esc = True
                elif ch == '"':
                    in_str = False
                continue
            if ch == '"':
                in_str = True
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    end = i + 1
                    break
        if end:
            try:
                found = json.loads(frag[:end])
            except Exception:
                pass
    return found


def run_cs(ctx, args, code, label, timeout=240, keep=False):
    """Write -> compile -> execute -> read result -> clean up. Returns a tool result dict."""
    if args.get("dry_run"):
        names = {k: _tool_name(ctx, k) for k in ("create_script", "refresh_unity", "execute_menu_item", "read_console")}
        return {"dryRun": True, "plan": [{"tool": names["create_script"], "arguments": {"path": TASK_PATH, "contents": "<%d chars of C#>" % len(code)}},
                                         {"tool": names["refresh_unity"], "arguments": {"mode": "force", "scope": "all", "compile": "request", "wait_for_ready": True}},
                                         {"tool": names["execute_menu_item"], "arguments": {"menu_path": MENU_PATH}},
                                         {"tool": names["read_console"], "arguments": {"action": "get", "types": ["log", "error"], "format": "plain"}}], "code": code}
    cs = _need(ctx, U, "create_script")
    rf = _need(ctx, U, "refresh_unity")
    em = _need(ctx, U, "execute_menu_item")
    rc = _need(ctx, U, "read_console")
    ctx.call(U, rc, {"action": "clear"}, 30)
    raw = ctx.call(U, cs, {"path": TASK_PATH, "contents": code}, 60)
    t0 = str((raw or {}).get("text") or "")
    if _failed(_parse(t0), t0):
        raise ToolkitError("could not write the helper script: " + t0[:300])
    ctx.call(U, rf, {"mode": "force", "scope": "all", "compile": "request", "wait_for_ready": True}, timeout)
    errs = str((ctx.call(U, rc, {"action": "get", "types": ["error"], "count": 20, "format": "plain"}, 60) or {}).get("text") or "")
    if re.search(r"error CS\d+", errs):
        _cleanup(ctx, keep)
        return {"ok": False, "error": "the generated C# did not compile (this is a Multi-Script bug or an unsupported Unity version)", "compileErrors": errs[-2500:],
                "hint": "Report these lines; the call changed nothing in your project."}
    ctx.call(U, rc, {"action": "clear"}, 30)
    raw = ctx.call(U, em, {"menu_path": MENU_PATH}, timeout)
    res, text = None, ""
    for _ in range(12):
        text = str((ctx.call(U, rc, {"action": "get", "types": ["log", "error", "warning"], "count": 60, "format": "plain"}, 60) or {}).get("text") or "")
        res = parse_marker(text)
        if res is not None:
            break
        time.sleep(1.0)
    _cleanup(ctx, keep)
    if res is None:
        menu_txt = str((raw or {}).get("text") or "")[:300]
        return {"ok": False, "error": "the task ran but returned no result line", "menu": menu_txt, "console": text[-1500:],
                "hint": "Is the Unity editor focused/not in play mode? Stop play mode and retry."}
    ok = bool(res.pop("ok", True))
    out = {"ok": ok}
    out.update(res)
    return out


def _tool_name(ctx, name):
    try:
        return _need(ctx, U, name)
    except Exception:
        return name


def _cleanup(ctx, keep):
    if keep:
        return
    try:
        ma = _need(ctx, U, "manage_asset")
        ctx.call(U, ma, {"action": "delete", "path": TASK_PATH}, 30)
        ctx.call(U, _need(ctx, U, "refresh_unity"), {"mode": "if_dirty", "scope": "all", "compile": "none", "wait_for_ready": False}, 30)
    except Exception:
        pass


