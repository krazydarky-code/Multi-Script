# ───────────────────────── C# literal helpers ─────────────────────────
def cs_str(s):
    s = str(s)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t") + '"'


def cs_f(x):
    x = float(x)
    if x == int(x) and abs(x) < 1e9:
        return "%df" % int(x)
    return repr(round(x, 6)) + "f"


def cs_bool(b):
    return "true" if b else "false"


def cs_vec(v):
    return "new Vector3(%s, %s, %s)" % tuple(cs_f(x) for x in v)


def cs_color(c, default="#ffffff"):
    col = color4(c if c is not None else default) or color4(default)
    col = list(col) + [1.0] * (4 - len(col))
    return "new Color(%s, %s, %s, %s)" % tuple(cs_f(x) for x in col[:4])


def cs_floats(xs):
    return "new float[] { " + ", ".join(cs_f(x) for x in xs) + " }"


def cs_strs(xs):
    return "new string[] { " + ", ".join(cs_str(x) for x in xs) + " }"


def fill(template, **vals):
    """Replace @@NAME@@ placeholders (C# bodies are full of braces, so no str.format)."""
    for k, v in vals.items():
        template = template.replace("@@" + k + "@@", str(v))
    left = re.findall(r"@@(\w+)@@", template)
    if left:
        raise ToolkitError("internal template placeholder left unfilled: " + ", ".join(sorted(set(left))))
    return template


