@tool(U, "ms_unity_run_csharp",
      "Run C# statements inside the Unity editor and get back what you put in the `R` dictionary (e.g. R[\"count\"] = n;). Wraps your code in an editor script, compiles it, executes it once, then deletes it. "
      "Helpers: Folder, SaveMat, Prim, FindGo/MustFind, RenderBounds, SetTag, Register (undo), MarkDirty, Warn.Add(). Use it for anything the other tools do not cover.",
      {"code": {"type": "string", "description": "Method-body statements (no class/method wrapper)."}, "lines": {"type": "array", "items": {"type": "string"}},
       "helpers": {"type": "string", "description": "Extra static members (methods/fields) placed next to Body()."}, "usings": {"type": "array", "items": {"type": "string"}},
       "keep_script": {"type": "boolean"}, "timeout_seconds": {"type": "integer"}}, [], writes=True)
def run_csharp(args, ctx):
    code = "\n".join(str(x) for x in as_list(args.get("lines"))) if args.get("lines") else str(args.get("code") or "")
    if not code.strip():
        raise ToolkitError("give `code` (or `lines`)", 'Example: R["objects"] = Object.FindObjectsOfType<Transform>().Length;')
    if re.search(r"^\s*(namespace|class|public\s+static\s+class)\b", code, re.M):
        raise ToolkitError("pass only method-body statements, not a class/namespace", "Use `helpers` for extra static methods.")
    for part, label in ((code, "code"), (str(args.get("helpers") or ""), "helpers")):
        if not _balanced(part):
            raise ToolkitError(f"unbalanced braces/parentheses in `{label}`", "Check for a missing } or ) before sending it to Unity.")
    usings = [u for u in (str(x).strip().rstrip(";") for x in as_list(args.get("usings"))) if re.match(r"^[\w.]+$", u)]
    src = csharp_task(code, "run_csharp", helpers=str(args.get("helpers") or ""), usings=usings)
    return run_cs(ctx, args, src, "run_csharp", timeout=int(num(args.get("timeout_seconds"), 240, 20, 900)), keep=boolean(args.get("keep_script"), False))


