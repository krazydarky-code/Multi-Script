#!/usr/bin/env python3
"""Generates docs/TOOLS_GUIDE.md - a plain-language catalogue of every tool Multi-Script exposes.
Reads the live registries (engine toolkits, bridge built-ins, Roblox companion), so it never drifts from the code.
Usage: python tools/gen_tools_guide.py"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "runtime"), os.path.join(ROOT, "tools")]
import engine_toolkit as T  # noqa: E402
import schema_audit as S  # noqa: E402

T.ensure_loaded()
B = S.load_bridge()

CATS = [  # (category, name fragments) - first match wins
    ("Audio", ["audio", "sound"]), ("NPCs and AI", ["npc", "navmesh", "enemy"]),
    ("Gameplay kits", ["gameplay_kit"]), ("Generators (buildings, paths, terrain, scatter, blockout, props)", ["building", "path_builder", "path", "terrain", "scatter", "blockout", "prop_generator", "curve"]),
    ("UI", ["ui", "gui"]), ("Animation and rigging", ["anim", "keyframe", "tween", "rig", "armature", "motion", "shape_keys", "sprite"]),
    ("Materials, lighting and rendering", ["material", "lighting", "light", "environment", "render", "post_processing", "graphics", "world", "shader", "camera", "studio"]),
    ("Particles and effects", ["particle", "vfx", "effect"]), ("Physics and collisions", ["physics", "collision", "constraint"]),
    ("Scripts and code", ["script", "csharp", "gdscript", "python", "api_lookup"]),
    ("Playtest, diagnostics and audits", ["playtest", "console", "profiler", "audit", "validate", "run_tests", "check", "output", "changes", "world_stats", "optimize", "screenshot", "verify"]),
    ("Project and assets", ["project", "asset", "package", "autoload", "input_map", "layer", "export", "import", "file", "list_files", "move", "resource", "prefab", "scene", "settings", "menu", "editor"]),
]


def cat(name):
    n = name.split("_", 2)[-1]
    for c, frags in CATS:
        if any(f in n for f in frags):
            return c
    return "Objects, nodes and general editing"


def first_sentence(text, limit=210):
    t = " ".join(str(text or "").split())
    out = ""
    for sent in re.split(r"(?<=[.!?])\s+", t):
        if out and len(out) + 1 + len(sent) > limit:
            break
        out = (out + " " + sent).strip()
        if len(out) >= 90:
            break
    if len(out) < 90 and len(t) > len(out):
        out = t[: limit - 1].rsplit(" ", 1)[0] + "…"
    return (out[: limit - 1].rstrip() + "…") if len(out) > limit else out


def modes(schema):
    props = (schema or {}).get("properties", {}) if isinstance(schema, dict) else {}
    for key in ("kind", "action", "preset", "prop", "mode", "type"):
        e = (props.get(key) or {}).get("enum")
        if e:
            return key + ": " + ", ".join(str(x) for x in e[:14]) + (" …" if len(e) > 14 else "")
    return ""


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


out = []
w = out.append
w("# Multi-Script tools guide\n")
w("_Generated by `tools/gen_tools_guide.py` from the live registries - do not edit by hand._\n")
w("## How the tools work\n")
w("1. You chat with an AI site (Notion AI, ChatGPT, Claude, Gemini, DeepSeek, Kimi, GLM, Qwen, Arena, Meta). The Multi-Script bar adds the tool list to the conversation.")
w("2. The model answers with a tool call. The extension parses it and sends it to the **local bridge** (a Python process on your computer).")
w("3. The bridge runs the tool: **native tools** (`ms_<engine>_*`) generate and run real engine code (Luau in Studio, C# in Unity, GDScript in Godot, Python in Blender) or write project files; **built-in tools** (`ms_*`) plan, audit, remember, read the screen or manage a workspace; the **Roblox companion** (`msrb_*`) edits the open place through a Studio plugin.")
w("4. The result (clipped or paginated according to Settings > Limits) goes back into the chat so the model can read, verify and continue.\n")
w("Tools marked **writes** change your project. Everything else only reads or plans. Native generators never bundle audio/art assets: you pass the asset ids or paths, and missing ones are reported as warnings.\n")

counts = T.counts()
w("## At a glance\n")
w("| Group | Tools |\n|---|---|")
for eng in ("roblox", "unity", "godot", "blender"):
    w(f"| Native {eng.title()} tools (`ms_{eng}_*`) | {counts.get(eng, 0)} |")
bt = [t for t in B.BUILTIN_TOOLS if isinstance(t, dict) and t['name'] not in B.RETIRED_FROM_CATALOGUE]
w(f"| Built-in bridge tools (`ms_*`, planning / memory / screen / workspace / catalogues) | {len(bt)} |")
w(f"| Roblox Studio companion (`msrb_*`) | {len(B.COMPANION_TOOLS)} |\n")

for eng in ("roblox", "unity", "godot", "blender"):
    tools = sorted((v for v in T.REGISTRY.values() if v["engine"] == eng), key=lambda v: v["name"])
    w(f"## Native {eng.title()} tools ({len(tools)})\n")
    groups = {}
    for v in tools:
        groups.setdefault(cat(v["name"]), []).append(v)
    for c in sorted(groups, key=lambda x: (x.startswith("Objects"), x)):
        w(f"### {c}\n")
        w("| Tool | What it does | Modes / kinds | Writes |\n|---|---|---|---|")
        for v in groups[c]:
            w(f"| `{v['name']}` | {esc(first_sentence(v['description']))} | {esc(modes(v['inputSchema']))} | {'yes' if v.get('writes') else ''} |")
        w("")

w(f"## Roblox Studio companion tools ({len(B.COMPANION_TOOLS)})\n")
w("Used when the Multi-Script Studio plugin is installed: selection, tree and property reads plus checkpointed edits and undo/redo.\n")
w("| Tool | What it does |\n|---|---|")
for t in B.COMPANION_TOOLS:
    w(f"| `{t['name']}` | {esc(first_sentence(t.get('description')))} |")
w("")

BUILTIN_GROUPS = [
    ("Bridge, engines and discovery", lambda n: n in {"ms_mcp_schema_audit", "ms_bridge_status", "ms_list_resources", "ms_read_resource", "ms_engine_catalog", "ms_engine_connection_test", "ms_call_engine_tool", "ms_engine_capability_map", "ms_roblox_capability_audit", "ms_engine_handoff", "ms_engine_command_planner"} or n.startswith("ms_native_")),
    ("Skills, specialists and orchestration", lambda n: any(k in n for k in ("skill", "virtual_tool", "direct_tool", "orchestrate", "studio_director", "mesh", "match_virtual", "workflow_plan", "parallel_tools"))),
    ("Memory and reasoning", lambda n: n.startswith("ms_memory_") or n in {"ms_sequential_thinking", "ms_agent_plan_then_act", "ms_agent_self_check", "ms_agent_context_recall"}),
    ("Screen, app and surface access", lambda n: n.startswith(("ms_surface_", "ms_app_"))),
    ("Software workspace (build programs from chat)", lambda n: n.startswith("ms_ws_")),
    ("Audio generation (ElevenLabs) and audio planning", lambda n: n in {"ms_elevenlabs_status", "ms_generate_sound_effect", "ms_list_generated_audio", "ms_audio_production"}),
    ("Audits and quality gates", lambda n: any(k in n for k in ("audit", "quality", "critic", "review", "checklist", "triage", "regression", "validation", "test_", "readiness", "release", "definition_of_done"))),
    ("Optimisation", lambda n: any(k in n for k in ("optimi", "budget", "profiler", "streaming", "efficiency"))),
]
seen = set()
w(f"## Built-in bridge tools ({len(bt)})\n")
for title, fn in BUILTIN_GROUPS:
    rows = [t for t in bt if t["name"] not in seen and fn(t["name"])]
    if not rows:
        continue
    for t in rows:
        seen.add(t["name"])
    w(f"### {title} ({len(rows)})\n")
    w("| Tool | What it does |\n|---|---|")
    for t in rows:
        w(f"| `{t['name']}` | {esc(first_sentence(t.get('description')))} |")
    w("")
rest = [t for t in bt if t["name"] not in seen]
w(f"### Design, production and engine-specialist advisors ({len(rest)})\n")
w("Planning tools that return a structured brief, checklist or review for the model to act on (they do not change your project themselves).\n")
w("| Tool | What it does |\n|---|---|")
for t in rest:
    w(f"| `{t['name']}` | {esc(first_sentence(t.get('description'), 150))} |")
w("")

path = os.path.join(ROOT, "docs", "TOOLS_GUIDE.md")
with open(path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(out))
print("wrote", path, len("\n".join(out)), "chars;", counts, len(bt), len(B.COMPANION_TOOLS))
